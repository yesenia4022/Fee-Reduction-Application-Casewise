export function accountNotFoundEmail(): string {
  return `Hello,

Thank you for submitting your Fee Reduction Application.

At this time, we are unable to locate an Enjoy! Online account associated with your application. In order for us to move forward with reviewing your Fee Reduction Application, you will first need to have an Enjoy! Online account.

If you have not yet created an account, please follow these steps:

1. Visit cityofpaloalto.org/enjoyonline:
https://ca-paloalto.civicrec.com/CA/palo-alto-ca/catalog

2. Click the "Log In/Create Account" button at the top-left of the page.

3. Select "Create Your Enjoy! Online Account."

4. Complete the form with your personal information.

Once your account has been created, please let us know so we can proceed with reviewing your Fee Reduction Application.

If you already have an Enjoy! Online account, please provide the email address associated with your account so we can locate it in our system.

If you have any questions or need assistance, please feel free to reach out.

Thank you,`;
}
